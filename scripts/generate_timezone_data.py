#!/usr/bin/env python3
"""Convert pinned tz-lookup JS and a tzdata wheel into flash-resident C++ tables.
Usage: generate_timezone_data.py tz.js tzdata.whl
No downloads occur during firmware builds. Inputs/hashes are recorded in output.
"""
from pathlib import Path
import hashlib, json, re, sys, zipfile, zlib
source=Path(sys.argv[1]).read_bytes()
text=source.decode()
packed=json.loads(re.search(r'var X=(".*?"),T=',text).group(1))
names=json.loads(re.search(r',T=(\[.*?\]);if',text).group(1))
wheel=Path(sys.argv[2]); archive=zipfile.ZipFile(wheel)
version=archive.read('tzdata/zoneinfo/tzdata.zi').decode().splitlines()[0]
out=['#pragma once','// Generated by scripts/generate_timezone_data.py; do not hand edit.',
     '// Geographic estimates: photostructure/tz-lookup (CC0); derived OSM/TBB boundary data.',
     '// tz.js SHA256: '+hashlib.sha256(source).hexdigest(),
     '// '+wheel.name+' SHA256: '+hashlib.sha256(wheel.read_bytes()).hexdigest(),
     '// IANA '+version, '#include <stddef.h>', 'namespace mcxtz {',
     'static constexpr char tree[]=']
# JSON escaping is valid C++ here (ASCII only); avoid trigraphs by splitting ?.
for at in range(0,len(packed),100):
    out.append(json.dumps(packed[at:at+100]).replace('?',r'\?'))
out[-1]+=';'
out+=['struct Zone {const char *name,*rule;unsigned short id;};','static constexpr Zone zones[]={']
ids=[zlib.crc32(name.encode(),1)&65535 for name in names]
assert len(set(ids))==len(ids) and 0 not in ids, 'Stable manual IDs collide; migrate explicitly'
for name,stable_id in zip(names,ids):
    raw=archive.read('tzdata/zoneinfo/'+name)
    rule=raw.rsplit(b'\n',2)[-2].decode()
    assert rule, name
    out.append('{'+json.dumps(name)+','+json.dumps(rule)+','+str(stable_id)+'},')
out+=['};','static constexpr unsigned count=sizeof(zones)/sizeof(zones[0]);',
'''// C++ port of tz-lookup's packed quadtree traversal (CC0).
// Approximate at geographic boundaries; callers offer a manual override.
static int lookup(double lat,double lon){
  if(!(lat>=-90&&lat<=90&&lon>=-180&&lon<=180))return -1;
  if(lat>=90){for(unsigned i=0;i<count;++i)if(!__builtin_strcmp(zones[i].name,"Etc/GMT"))return int(i);}
  double s=48*(180+lon)/360.00000000000006,u=24*(90-lat)/180.00000000000003;
  int x=int(s),y=int(u),v=-1,at=96*y+2*x;
  auto read=[](int p){return 56*int(tree[p])+int(tree[p+1])-1995;};
  int k=read(at);
  for(unsigned depth=0;k+int(count)<3136&&depth<32;++depth){
    v+=k+1;u=2*(u-y);s=2*(s-x);y=int(u);x=int(s);
    at=8*v+4*y+2*x+2304;
    if(at<0||size_t(at+1)>=sizeof(tree)-1)return -1;
    k=read(at);
  }
  const int index=k+int(count)-3136;
  return index>=0&&index<int(count)?index:-1;
}
}''']
path=Path(__file__).resolve().parents[1]/'firmware/display-prototype/timezone/zone_data.h'
path.write_text('\n'.join(out)+'\n')
print(version, len(names), 'zones;',len(packed),'tree bytes')
